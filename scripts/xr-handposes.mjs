#!/usr/bin/env node
/**
 * Bakes the recorded hand poses that ship with Meta's IWER (MIT licensed; relaxed, pinch, point)
 * into src/xr/handposes.ts for the ghost-hand hints: 25 joint positions per pose in a wrist frame
 * (x = toward the little finger of a left hand, y = toward the middle knuckle, z = out of the palm), in mm.
 *   node scripts/xr-handposes.mjs
 */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { relaxedHandPose } from "../node_modules/iwer/lib/device/configs/hand/relaxed.js";
import { pinchHandPose } from "../node_modules/iwer/lib/device/configs/hand/pinch.js";
import { pointHandPose } from "../node_modules/iwer/lib/device/configs/hand/point.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sub = (a, b) => a.map((v, i) => v - b[i]);
const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
const unit = (a) => a.map((v) => v / Math.hypot(...a));
const cross = (a, b) => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];

function bake(pose) {
  const J = pose.jointTransforms;
  const at = (n) => [J[n].offsetMatrix[12], J[n].offsetMatrix[13], J[n].offsetMatrix[14]];
  const w = at("wrist");
  const f = unit(sub(at("middle-finger-phalanx-proximal"), w));
  const m = J["middle-finger-metacarpal"].offsetMatrix;
  let n = [-m[4], -m[5], -m[6]];
  n = unit(sub(n, f.map((v) => v * dot(n, f))));
  const s = unit(cross(f, n));
  const out = [];
  for (const name of Object.keys(J)) {
    const d = sub(at(name), w);
    out.push(Math.round(dot(d, s) * 10000) / 10, Math.round(dot(d, f) * 10000) / 10, Math.round(dot(d, n) * 10000) / 10);
  }
  return out;
}

const radii = Object.values(relaxedHandPose.jointTransforms).map((j) => Math.round(j.radius * 10000) / 10);
const src = `// Generated by scripts/xr-handposes.mjs from the hand poses in Meta's IWER (MIT licence).
/**
 * Ghost-hand poses: 25 WebXR hand joints (wrist first, then thumb, index, middle, ring, pinky from
 * metacarpal to tip) as x, y, z in millimetres in a wrist frame: x toward the little finger of a left
 * hand (its thumb is at -x), y toward the middle knuckle, z out of the palm. Mirror x for a right hand.
 */
export const POSES = {
  relaxed: [${bake(relaxedHandPose).join(", ")}],
  pinch: [${bake(pinchHandPose).join(", ")}],
  point: [${bake(pointHandPose).join(", ")}],
};

/** Joint radii (mm) of the relaxed pose. */
export const RADII = [${radii.join(", ")}];
`;
await fs.writeFile(path.join(ROOT, "src", "xr", "handposes.ts"), src);
console.log("wrote src/xr/handposes.ts");
